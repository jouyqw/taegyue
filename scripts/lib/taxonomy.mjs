export const topicOf = (slug) => TOPICS.find((t) => t.re.test(slug));

const grab = (html, re) => (html.match(re) || [])[1]?.trim() || '';
const stripTags = (v = '') => String(v).replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
const decode = (v = '') => v.replaceAll('&amp;', '&').replaceAll('&lt;', '<').replaceAll('&gt;', '>')
  .replaceAll('&quot;', '"').replaceAll('&#39;', "'").replaceAll('&apos;', "'");

/** cloudflare_pages_upload/blog/*.html 를 읽어 글 목록을 만듭니다. */
export function loadPosts() {
  return readdirSync(BLOG_DIR)
    .filter((f) => f.endsWith('.html') && f !== 'index.html')
    .map((file) => {
      const html = readFileSync(path.join(BLOG_DIR, file), 'utf8');
      const slug = file.replace(/\.html$/, '');
      const rawTitle = grab(html, /<h1[^>]*>([\s\S]*?)<\/h1>/i) || grab(html, /<title>([\s\S]*?)<\/title>/i);
      return {
        file,
        slug,
        href: `/blog/${slug}`,
        title: decode(stripTags(rawTitle)).replace(/\s*\|\s*법무법인.*$/, ''),
        description: decode(grab(html, /<meta\s+name=["']description["']\s+content=["']([^"']+)["']/i)),
        date: grab(html, /"datePublished"\s*:\s*"([^"]+)"/i) || grab(html, /<time[^>]*datetime=["']([^"']+)["']/i) || '',
        region: regionOf(slug),
        topic: topicOf(slug),
      };
    })
    .sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

/**
 * 한 글에 붙일 관련글 6~8개를 고릅니다.
 * 같은 주제 → 같은 지역 → 다른 지역의 같은 주제 → 최신 순으로 채웁니다.
 */
export function relatedFor(post, posts, count = 8) {
  const pick = [];
  const push = (list) => {
    for (const p of list) {
      if (p.slug === post.slug || pick.some((x) => x.slug === p.slug)) continue;
      pick.push(p);
      if (pick.length >= count) return;
    }
  };
  const sameTopicSameRegion = posts.filter((p) => p.topic.key === post.topic.key && p.region.key === post.region.key);
  const sameRegion = posts.filter((p) => p.region.key === post.region.key);
  const sameTopic = posts.filter((p) => p.topic.key === post.topic.key);
  push(sameTopicSameRegion);
  push(sameTopic);
  push(sameRegion);
  push(posts);
  return pick.slice(0, count);
}
